import { readFileSync,readdirSync } from "node:fs";
import { randomUUID } from "node:crypto";
import { PGlite } from "@electric-sql/pglite";
import { expect,it } from "vitest";

it("persists purchase identity, freezes pricing, grants calendar access once and preserves reversals", async()=>{
 const db=new PGlite();
 try {
 await db.exec(readFileSync("server/billing/tests/referralBootstrap.sql","utf8"));
 for(const file of readdirSync("supabase/migrations").sort().filter(f=>/^(20260718|20260728|202608280001|20260906|20260907|20260908)/.test(f))) await db.exec(readFileSync(`supabase/migrations/${file}`,"utf8"));
 await db.exec(`alter table billing_plans add column if not exists is_public boolean not null default true;
 alter table billing_plans add column if not exists requires_legacy_founder_eligibility boolean not null default false;
 create table if not exists billing_user_entitlements(id uuid default gen_random_uuid(),user_id uuid,entitlement_key text);`);
 for(const file of ["202610280001_billing_plan_duration_configuration.sql","202610280002_prepaid_checkout_recovery.sql"]) await db.exec(readFileSync(`supabase/migrations/${file}`,"utf8"));
 await db.exec(readFileSync("supabase/rollbacks/202610280002_prepaid_checkout_recovery.rollback.sql","utf8"));
 await db.exec(readFileSync("supabase/migrations/202610280002_prepaid_checkout_recovery.sql","utf8"));
 await db.exec(readFileSync("supabase/diagnostics/202610280001_billing_plan_duration_configuration.sql","utf8"));
 await db.exec(readFileSync("supabase/diagnostics/202610280002_prepaid_checkout_recovery.sql","utf8"));
 const u=randomUUID(),p=randomUUID(),key=randomUUID(),alias=randomUUID();
 await db.query("insert into auth.users(id,email) values($1,'test@example.test')",[u]);
 await db.query("insert into profiles(id,email,nome,role) values($1,'test@example.test','Synthetic','student')",[u]);
 await db.query("insert into billing_plans(id,slug,name,price_cents) values($1,'normal-test','Normal',1190)",[p]);
 const prepare=async(k=key,months=6,method="pix")=>(await db.query<{a:any}>("select prepare_prepaid_checkout($1,$2,'normal-test',$3,$4,'test@example.test') as a",[u,k,months,method])).rows[0].a;
 await expect(prepare()).rejects.toThrow("Duração desativada");
 await db.query("insert into billing_plan_durations(plan_id,months,enabled,discount_bps) values($1,6,true,500),($1,12,true,0)",[p]);
 const referrer=randomUUID(),version=randomUUID();
 await db.query("insert into auth.users(id,email) values($1,'referrer@example.test')",[referrer]);
 await db.query("insert into profiles(id,email,nome,role) values($1,'referrer@example.test','Synthetic referrer','student')",[referrer]);
 await db.query("insert into referral_campaign_versions(id,enabled,title,description,goal,reward_days,benefit,discount,whatsapp_label,whatsapp_message) values($1,true,'Test','Test',1,10,'percent',10,'Test','Test')",[version]);
 await db.query("insert into referral_campaign_current values(1,$1)",[version]);
 await db.query("insert into student_referrals(referrer_id,referee_id,version_id) values($1,$2,$3)",[referrer,u,version]);
 const a=await prepare(); expect(a.snapshot.total_cents).toBe(6105);
 expect(a.snapshot.referral_discount_cents).toBe(678);
 expect((await prepare(alias)).id).toBe(a.id);
 await db.query("update billing_plans set price_cents=5000 where id=$1",[p]);
 await db.query("update billing_plan_durations set enabled=false,discount_bps=9000 where plan_id=$1",[p]);
 expect((await prepare()).snapshot.total_cents).toBe(6105);
 await expect(prepare(randomUUID(),12)).rejects.toThrow("outras condições");
 const claim=async()=>(await db.query<{v:boolean}>("select claim_prepaid_submission($1,$2) as v",[u,a.id])).rows[0].v;
 expect(await claim()).toBe(true); expect(await claim()).toBe(false);
 const reference=`payment:${a.payment_id}:subscription:${a.snapshot.subscription_id}`;
 const result={paymentId:a.payment_id,subscriptionId:a.snapshot.subscription_id,checkoutUrl:"https://www.mercadopago.com.br/synthetic",externalReference:reference,amountCents:6105};
 await db.query("select complete_prepaid_submission($1,$2,$3::jsonb,'mp-synthetic')",[u,a.id,JSON.stringify(result)]);
 const apply=()=>db.query("select * from apply_approved_prepaid_payment($1,'mp-synthetic','approved',null,now(),30)",[a.payment_id]);
 const applied=(await apply()).rows[0] as any;
 const again=(await apply()).rows[0] as any;
 expect(again.already_applied).toBe(true); expect(again.period_end).toEqual(applied.period_end);
 expect((await db.query<{ok:boolean}>("select $1::timestamptz = add_billing_access_duration($2::timestamptz,6,'months') as ok",[applied.period_end,applied.period_start])).rows[0].ok).toBe(true);
 await db.query("select referral_reconcile_payment($1)",[a.payment_id]);
 await db.query("select referral_reconcile_payment($1)",[a.payment_id]);
 expect((await db.query<{n:number}>("select count(*)::int n from referral_rewards where user_id=$1 and revoked_at is null",[referrer])).rows[0].n).toBe(1);
 expect((await prepare(alias)).id).toBe(a.id); // Alias survives approval too.
 const rows=(await db.query<{n:number}>("select count(*)::int n from billing_payments where user_id=$1",[u])).rows;
 expect(rows[0].n).toBe(1);
 await db.query("select * from recalculate_mercadopago_access_after_reversal($1,'refunded','refunded',null)",[a.payment_id]);
 await db.query("select referral_reconcile_payment($1)",[a.payment_id]);
 expect((await db.query<{n:number}>("select count(*)::int n from referral_rewards where user_id=$1 and revoked_at is null",[referrer])).rows[0].n).toBe(0);
 expect((await prepare()).payment_id).toBe(a.payment_id);
 await db.query("update billing_plan_durations set enabled=true,discount_bps=0 where plan_id=$1 and months=12",[p]);
 await db.query("update billing_plans set requires_legacy_founder_eligibility=true where id=$1",[p]);
 await expect(prepare(randomUUID(),12)).rejects.toThrow("Founder eligibility required");
 await db.query("insert into billing_user_entitlements(user_id,entitlement_key) values($1,'legacy_founder_eligible')",[u]);
 const annual=await prepare(randomUUID(),12); expect(annual.payment_id).not.toBe(a.payment_id);expect(annual.snapshot.total_cents).toBe(60000);
 const annualApplied=(await db.query("select * from apply_approved_prepaid_payment($1,'annual','approved',null,now(),30)",[annual.payment_id])).rows[0] as any;
 expect((await db.query<{ok:boolean}>("select $1::timestamptz = add_billing_access_duration($2::timestamptz,12,'months') as ok",[annualApplied.period_end,annualApplied.period_start])).rows[0].ok).toBe(true);
 await db.query("select * from recalculate_mercadopago_access_after_reversal($1,'chargeback','charged_back',null)",[annual.payment_id]);
 await expect(db.exec(readFileSync("supabase/rollbacks/202610280002_prepaid_checkout_recovery.rollback.sql","utf8"))).rejects.toThrow("Rollback blocked");
 await db.exec("rollback");
 await db.exec("set role authenticated");
 await expect(db.query("select * from billing_prepaid_attempts")).rejects.toThrow();
 await expect(prepare()).rejects.toThrow();
 }catch(error){console.error((error as any).where);throw error;}finally{await db.close();}
},60000);
